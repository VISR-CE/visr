#!/usr/bin/env python3
"""Writes port/ios/host/blue_noise.h: two 64x64 blue-noise masks for the present pass's dither (display.scene_precision).

Each mask is a rank order made by void and cluster (Ulichney, 1993) on a torus, so it tiles: every value from 0 to 4095
appears once, stored as rank >> 4 (each 8-bit value 16 times, a uniform histogram). The second mask starts from a
different seed. The present shader adds the two (minus one) for triangular noise one output level wide each side.

The output is deterministic. Run without arguments to rewrite the header, or with --check to fail if it is stale
(slow: about a minute in pure Python, so public CI checks the header's properties instead, tools/test_present_dither.py).
"""
import argparse
import math
import pathlib
import random
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = ROOT / 'port/ios/host/blue_noise.h'
SIZE = 64
SIGMA = 1.9


def kernel():
    """the Gaussian energy of a point at each toroidal offset"""
    values = []
    for y in range(SIZE):
        dy = min(y, SIZE - y)
        for x in range(SIZE):
            dx = min(x, SIZE - x)
            values.append(math.exp(-(dx * dx + dy * dy) / (2.0 * SIGMA * SIGMA)))
    return values


def add_energy(energy, kernel_values, index, sign):
    py, px = divmod(index, SIZE)
    for y in range(SIZE):
        row = ((y - py) % SIZE) * SIZE
        base = y * SIZE
        for x in range(SIZE):
            energy[base + x] += sign * kernel_values[row + (x - px) % SIZE]


def void_and_cluster(seed):
    count = SIZE * SIZE
    kernel_values = kernel()
    rng = random.Random(seed)
    # the initial binary pattern: a tenth of the cells, then relaxed until the tightest cluster is the largest void
    ones = set(rng.sample(range(count), count // 10))
    energy = [0.0] * count
    for index in ones:
        add_energy(energy, kernel_values, index, 1.0)
    while True:
        cluster = max(ones, key=lambda index: energy[index])
        ones.discard(cluster)
        add_energy(energy, kernel_values, cluster, -1.0)
        void = min((index for index in range(count) if index not in ones), key=lambda index: energy[index])
        if void == cluster:
            ones.add(cluster)
            add_energy(energy, kernel_values, cluster, 1.0)
            break
        ones.add(void)
        add_energy(energy, kernel_values, void, 1.0)
    rank = [0] * count
    # phase 1: remove the tightest clusters from a copy of the pattern, ranking downward
    pattern = set(ones)
    pattern_energy = list(energy)
    for value in range(len(ones) - 1, -1, -1):
        cluster = max(pattern, key=lambda index: pattern_energy[index])
        pattern.discard(cluster)
        add_energy(pattern_energy, kernel_values, cluster, -1.0)
        rank[cluster] = value
    # phases 2 and 3: fill the largest voids, ranking upward
    pattern = set(ones)
    for value in range(len(ones), count):
        void = min((index for index in range(count) if index not in pattern), key=lambda index: energy[index])
        pattern.add(void)
        add_energy(energy, kernel_values, void, 1.0)
        rank[void] = value
    return rank


def header_text():
    masks = [void_and_cluster(seed) for seed in (1, 2)]
    lines = ['/* Generated by tools/gen_blue_noise.py: do not edit. Two 64x64 blue-noise masks (void and cluster on a',
             'torus, so they tile), interleaved as the red and green of an RG8 texture, each value rank >> 4 of the',
             'mask\'s 4,096 ranks (every 8-bit value 16 times). The present pass\'s dither (gpu_metal.m). */',
             '#ifndef BLUE_NOISE_H', '#define BLUE_NOISE_H', '', '#define BLUE_NOISE_SIZE 64', '',
             'static const unsigned char blue_noise_rg[BLUE_NOISE_SIZE * BLUE_NOISE_SIZE * 2] =', '{']
    values = []
    for index in range(SIZE * SIZE):
        values.append(masks[0][index] >> 4)
        values.append(masks[1][index] >> 4)
    for start in range(0, len(values), 32):
        lines.append('\t' + ', '.join(str(value) for value in values[start:start + 32]) + ',')
    lines += ['};', '', '#endif', '']
    return '\n'.join(lines)


def main(arguments=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='fail if the header is stale')
    options = parser.parse_args(arguments)
    text = header_text()
    if options.check:
        if HEADER.read_text() != text:
            print(f'{HEADER.relative_to(ROOT)} is stale: run tools/gen_blue_noise.py', file=sys.stderr)
            return 1
        return 0
    HEADER.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
