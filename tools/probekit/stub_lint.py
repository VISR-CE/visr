"""Lint rule 2 of the stub design (tools/test_probe_conventions.py): a probe's own definition of a name the shared
stub files cover (port/ios/tests/host_stubs.c and port_stubs.c, generated by tools/host_stubs.py) either returns state
the probe sets up, and says so with `/* fake: <why> */` on its line or the line above, or is a copy of the default the
probe should drop. A header under port/ios/tests named like a production header is a hand copy of its
declarations unless it is one of the stand-ins tools/host_stubs.py generates (STAND_INS). Definitions are found in C files under port/ios/tests and in the C text of Python files under
tools/, by name: a return type, the name, a parameter list and an opening brace, at the start of a line."""
from __future__ import annotations

import functools
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TOOLS = ROOT / 'tools'
PROBES = ROOT / 'port/ios/tests'
GENERATED = {'host_stubs.c', 'port_stubs.c'}
C_SUFFIXES = {'.c', '.m', '.h', '.in', '.cpp', '.mm', '.inc'}
FAKE = re.compile(r'/\*\s*fake:\s*(?!\*/)\S')


@functools.lru_cache(maxsize=None)
def covered() -> frozenset[str]:
    """Every name either stub file gives a weak default."""
    if str(TOOLS) not in sys.path:
        sys.path.insert(0, str(TOOLS))
    import host_stubs
    return frozenset(host_stubs.collect()) | frozenset(host_stubs.collect_seams()[0])


ATTRIBUTE = r'__attribute__\s*\(\((?:[^()]|\([^()]*\))*\)\)'
PARAMETERS = r'\((?:[^;{}()]|\((?:[^;{}()]|\([^()]*\))*\))*\)'   # two levels of nesting: function-pointer parameters
OPENING = r'(?:[rbfuRBFU]{0,2}["\'])?'   # a definition at the start of a Python string literal's text


def marked_above(line: str) -> bool:
    """The line above a definition marks it only when it is nothing but a fake comment (inside a Python string, the
    quotes and an escaped newline may surround it)."""
    text = re.sub(r'^\s*[rbfuRBFU]{0,2}["\']|(?:\\n)?["\']?\s*$', '', line.strip())
    return bool(re.fullmatch(r'/\*\s*fake:\s*(?!\*/)\S.*?\*/', text.strip()))


def definitions(text: str, names, comments: str = 'c') -> list[tuple[str, int, bool]]:
    """(name, line, marked as a fake) for each definition of a covered name in `text`. Comments are blanked first
    (C comments for a C file; for a Python file, `comments='python'` leaves the text whole, since its C sits in
    string literals). A marker is `/* fake: <why> */` with a reason, on the definition's line or alone on the line
    above."""
    names = sorted(names, key=len, reverse=True)
    if not names:
        return []
    from probekit import source as probe_source
    scanned = probe_source.mask(text, strings=False) if comments == 'c' else text
    pattern = re.compile(r'^[ \t]*' + OPENING + r'(?:' + ATTRIBUTE + r'\s*)*(?:[A-Za-z_][\w \t\*]*?[\s\*])?('
                         + '|'.join(map(re.escape, names)) + r')[ \t]*' + PARAMETERS + r'\s*(?:' + ATTRIBUTE
                         + r'\s*)?\{', re.MULTILINE)
    lines = text.split('\n')
    found = []
    for match in pattern.finditer(scanned):
        prefix = re.sub(ATTRIBUTE, '', scanned[match.start():match.start(1)]).lstrip(' \t"\'rbfuRBFU')
        if re.search(r'\b(?:return|if|while|for|switch|else)\b|[=,(]', prefix):
            continue
        line = text.count('\n', 0, match.start(1))
        marked = bool(FAKE.search(lines[line])) or (line > 0 and marked_above(lines[line - 1]))
        found.append((match.group(1), line + 1, marked))
    return found


def linted_files() -> list[Path]:
    # (the generator, this detector, and the rule's own tests, whose fixtures are deliberate unmarked copies)
    python = [path for path in TOOLS.rglob('*.py') if path.name not in {'host_stubs.py', 'stub_lint.py',
                                                                         'test_probe_conventions.py'}
              and '__pycache__' not in path.parts]
    probes = [path for path in PROBES.rglob('*') if path.is_file() and path.suffix in C_SUFFIXES
              and path.name not in GENERATED]
    return sorted(python + probes)


def name_of(path: Path) -> str:
    """The repository-relative path (a file outside the repository, as a test's, keeps its own)."""
    return str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)


def findings(files=None) -> dict[str, list[tuple[str, int]]]:
    """file (relative to the repository) -> the unmarked definitions of covered names in it."""
    names = covered()
    found = {}
    for path in linted_files() if files is None else files:
        text = path.read_text(encoding='latin-1')
        style = 'python' if path.suffix == '.py' else 'c'
        unmarked = [(name, line) for name, line, fake in definitions(text, names, style) if not fake]
        if unmarked:
            found[name_of(path)] = unmarked
    return found



@functools.lru_cache(maxsize=None)
def production_header_names() -> frozenset[str]:
    """The file names of the headers under source/ and port/ (not the probes' own, not third-party code)."""
    names = set()
    for base in ('source', 'port'):
        for header in (ROOT / base).rglob('*.h'):
            parts = header.relative_to(ROOT).parts
            if parts[:3] != ('port', 'ios', 'tests') and 'third_party' not in parts:
                names.add(header.name)
    return frozenset(names)


def generated_headers() -> frozenset[str]:
    """The headers tools/host_stubs.py writes (STAND_INS), as repository paths."""
    if str(TOOLS) not in sys.path:
        sys.path.insert(0, str(TOOLS))
    import host_stubs
    return frozenset(name_of(host_stubs.STAND_IN_DIRECTORY / name) for name in host_stubs.STAND_INS)


def hand_copied_headers(headers=None, production=None, generated=None) -> list[str]:
    """Headers under port/ios/tests named like a production header that tools/host_stubs.py does not write (a
    GENERATED first line is not enough: the file must be a STAND_INS entry, which --check compares)."""
    production = production_header_names() if production is None else production
    generated = generated_headers() if generated is None else generated
    headers = PROBES.rglob('*.h') if headers is None else headers
    return sorted(name_of(header) for header in headers if header.name in production
                  and name_of(header) not in generated)
